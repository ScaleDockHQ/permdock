import { basename, join } from "node:path";

import type { DoctorFiles, DoctorFinding } from "../shared/doctor-types.ts";
import type { PermDockConfig } from "../types.ts";

import { rel, sqlFiles } from "../files.ts";
import { nodeFiles } from "../shared/doctor-files.ts";
import { HOOK_MARKER } from "../sql/markers.ts";
import { readSupabaseConfig, supabaseConfig } from "../supabase-config.ts";
import { resolveSchemas } from "../supabase-schemas.ts";

const SCHEMAS = "supabase/schemas";
const MIGRATIONS = "supabase/migrations";

const CREATES_HOOK =
  /\bcreate\s+(?:or\s+replace\s+)?function\s+[\w."]*custom_access_token_hook\b/iu;
const DROPS_HOOK =
  /\bdrop\s+function\s+(?:if\s+exists\s+)?[\w."]*custom_access_token_hook\b/iu;
const GRANTS_HOOK =
  /\bgrant\s+execute\s+on\s+function\s+[\w."]*custom_access_token_hook\s*\(\s*jsonb\s*\)\s+to\s+supabase_auth_admin\b/iu;
const DEFINES_HELPER =
  /\bcreate\s+(?:or\s+replace\s+)?function\s+[\w."]*permdock_has\s*\(/iu;
const CALLS_HELPER =
  /\b(?:permdock_has|(?:permitted|member)_[a-z][a-z0-9_]*_ids)\s*\(/iu;

function uncommented(text: string): string {
  return text.replaceAll(/--[^\n]*/gu, "").replaceAll(/\/\*[\s\S]*?\*\//gu, "");
}

/** Whether `text` starts with a line `rls generate` or `supabase hook generate` writes. */
function generatedByPermDock(text: string): boolean {
  return (
    text.startsWith("-- permdock:") ||
    text.startsWith("-- generated by permdock")
  );
}

/**
 * PD042: under migra, a hook declared under `supabase/schemas` reaches the
 * database through `supabase db diff`, which drops its `supabase_auth_admin`
 * grants. pg-delta keeps them, so the check runs only for `migra`. A function
 * created (or dropped and created again) without them is executable by
 * `public` and not by the auth server, so a migration at or after the one
 * that creates it must carry the grants.
 */
export function pd042(
  cwd: string,
  config: PermDockConfig,
  files: DoctorFiles = nodeFiles,
): readonly DoctorFinding[] {
  if (
    config.supabase?.hook === undefined ||
    resolveSchemas(cwd, config).mode !== "migra"
  ) {
    return [];
  }
  const declared = sqlFiles(cwd, [SCHEMAS]).some((file) =>
    files.read(file).startsWith(`${HOOK_MARKER} `),
  );
  if (!declared) {
    return [];
  }
  const migrations = sqlFiles(cwd, [MIGRATIONS]).map((file) => ({
    file,
    text: uncommented(files.read(file)),
  }));
  const created = migrations.findIndex(({ text }) => CREATES_HOOK.test(text));
  const dropped = migrations.findLastIndex(({ text }) => DROPS_HOOK.test(text));
  const needed = Math.max(created, dropped);
  if (needed === -1) {
    return [];
  }
  const granted = migrations.findLastIndex(({ text }) =>
    GRANTS_HOOK.test(text),
  );
  if (granted >= needed) {
    return [];
  }
  const at = rel(cwd, migrations[needed]?.file ?? MIGRATIONS);
  return [
    {
      code: "PD042",
      severity: "error",
      message: `${at} creates custom_access_token_hook from supabase/schemas, and no migration from it on grants it to supabase_auth_admin: supabase db diff drops those grants, so the auth server cannot call the hook and public can`,
      fix: "switch to pg-delta, which keeps the grants ([experimental.pgdelta] enabled = true and no supabase.schemas: 'migra'), or generate the grants with permdock supabase hook generate --grants-out (or rls generate --split ...,hook --grants-out) into a new file from supabase migration new, after the db diff migration",
    },
  ];
}

/** The PermDock-generated files under the declarative schema directory. */
function generatedSchemaFiles(
  cwd: string,
  schemaDir: string,
  files: DoctorFiles,
): readonly string[] {
  if (!files.exists(join(cwd, schemaDir))) {
    return [];
  }
  return sqlFiles(cwd, [schemaDir]).filter((file) =>
    generatedByPermDock(files.read(file)),
  );
}

/**
 * PD068: PermDock generates for pg-delta (the default), but
 * `supabase/config.toml` does not set `[experimental.pgdelta] enabled =
 * true`, so Supabase CLI 2.x diffs the schema files with migra. migra drops
 * the hook's `supabase_auth_admin` grants and the helpers' privileges, and
 * PermDock wrote no `--grants-out` file to restore them.
 */
export function pd068(
  cwd: string,
  config: PermDockConfig,
  files: DoctorFiles = nodeFiles,
): readonly DoctorFinding[] {
  const read = readSupabaseConfig(cwd);
  if (read?.ok !== true || read.config.pgDelta?.enabled === true) {
    return [];
  }
  const schemas = resolveSchemas(cwd, config);
  if (schemas.mode !== "pg-delta") {
    return [];
  }
  const [first] = generatedSchemaFiles(cwd, schemas.schemaDir, files);
  if (first === undefined) {
    return [];
  }
  return [
    {
      code: "PD068",
      severity: "error",
      message: `${rel(cwd, first)} is written for pg-delta, but supabase/config.toml does not set [experimental.pgdelta] enabled = true, so the Supabase CLI diffs it with migra and drops the hook and helper grants`,
      fix: "add [experimental.pgdelta] with enabled = true to supabase/config.toml (Supabase CLI 2.119 or later), or set supabase.schemas: 'migra' in permdock.config.ts and regenerate with --grants-out",
    },
  ];
}

/**
 * PD069: leftovers of declarative schemas on migra in a pg-delta project:
 * `[db.migrations] schema_paths`, which pg-delta's dependency order makes
 * unnecessary, and numbered `NNN_permdock_<part>.sql` files that duplicate
 * the per-schema layout `rls generate --split` now writes.
 */
export function pd069(
  cwd: string,
  config: PermDockConfig,
  files: DoctorFiles = nodeFiles,
): readonly DoctorFinding[] {
  const schemas = resolveSchemas(cwd, config);
  if (schemas.mode !== "pg-delta") {
    return [];
  }
  const findings: DoctorFinding[] = [];
  if ((supabaseConfig(cwd).schemaPaths ?? []).length > 0) {
    findings.push({
      code: "PD069",
      severity: "warning",
      message:
        "supabase/config.toml sets [db.migrations] schema_paths, which pg-delta does not need: it orders the schema files by their dependencies",
      fix: "remove schema_paths from [db.migrations] in supabase/config.toml",
    });
  }
  for (const file of generatedSchemaFiles(cwd, schemas.schemaDir, files)) {
    if (/^\d+_permdock_/u.test(basename(file))) {
      findings.push({
        code: "PD069",
        severity: "warning",
        message: `${rel(cwd, file)} is a numbered part from declarative schemas on migra; under pg-delta, rls generate --split writes the per-schema layout instead`,
        fix: "delete the numbered parts, run permdock rls generate --split without --out, then supabase db schema declarative sync",
      });
    }
  }
  return findings;
}

/** The `[db.migrations] schema_paths` globs of `supabase/config.toml`, or Supabase's default. */
function schemaPaths(cwd: string): readonly string[] {
  const paths = supabaseConfig(cwd).schemaPaths ?? [];
  return paths.length === 0 ? ["./schemas/**/*.sql"] : paths;
}

/** Schema files in the order `supabase db diff` applies them: each glob in turn, sorted within it. */
function orderedSchemaFiles(cwd: string): readonly string[] {
  return sqlFiles(join(cwd, "supabase"), schemaPaths(cwd), { order: "entry" });
}

/**
 * PD043: under migra, `db diff` applies schema files in `schema_paths`
 * order, so a policy that calls `permdock_has` or `permitted_<scope>_ids`
 * before the file that defines them fails to apply. pg-delta orders by
 * dependencies instead.
 */
export function pd043(
  cwd: string,
  config: PermDockConfig,
  files: DoctorFiles = nodeFiles,
): readonly DoctorFinding[] {
  if (resolveSchemas(cwd, config).mode !== "migra") {
    return [];
  }
  if (!files.exists(join(cwd, SCHEMAS))) {
    return [];
  }
  const schemas = orderedSchemaFiles(cwd).map((file) => ({
    file,
    text: uncommented(files.read(file)),
  }));
  const helpers = schemas.findIndex(({ text }) => DEFINES_HELPER.test(text));
  const defined = sqlFiles(cwd, [SCHEMAS]).find((file) =>
    DEFINES_HELPER.test(uncommented(files.read(file))),
  );
  if (helpers === -1) {
    return defined === undefined
      ? []
      : [
          {
            code: "PD043",
            severity: "warning",
            message: `${rel(cwd, defined)} defines the PermDock helpers, but schema_paths in supabase/config.toml does not list it, so supabase db diff never applies it`,
            fix: `add it to [db.migrations] schema_paths before every file that calls permdock_has, permitted_<scope>_ids or member_<scope>_ids`,
          },
        ];
  }
  const helperFile = rel(cwd, schemas[helpers]?.file ?? "");
  return schemas
    .slice(0, helpers)
    .filter(({ text }) => CALLS_HELPER.test(text))
    .map(({ file }) => ({
      code: "PD043",
      severity: "warning",
      message: `${rel(cwd, file)} calls the PermDock helpers, but schema_paths applies it before ${helperFile}, which defines them`,
      fix: `list ${helperFile} earlier in [db.migrations] schema_paths, or give it a lower number, such as 056_permdock_helpers.sql before 060_policies.sql`,
    }));
}
