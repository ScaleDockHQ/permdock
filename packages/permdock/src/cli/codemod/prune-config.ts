/** What `permdock codemod config --prune --json` prints. */
export type PruneReport = {
  readonly file: string;
  readonly check: boolean;
  /** Keys removed, or with `check` the keys that would be. */
  readonly removed: readonly string[];
  /** Keys equal to their default whose removal changed a generated file. */
  readonly kept: readonly { readonly key: string; readonly why: string }[];
  /** Keys equal to their default that the source edit could not reach. */
  readonly unreachable: readonly string[];
};

/** Every generated file for `config`, as sorted `path` and text pairs. */
async function outputsOf(
  cwd: string,
  file: string,
  config: PermDockConfig,
): Promise<readonly string[]> {
  const derived = (
    await withDerivedDefaults(cwd, file, { config, warnings: [] })
  ).config;
  if (derived.policy === undefined) {
    return [];
  }
  const policy = await requirePolicy(
    cwd,
    derived.policy,
    "codemod config --prune needs the policy to regenerate",
  );
  const plugins = (derived.plugins ?? []).filter(isPermDockPlugin);
  const { emitted } = await emitPluginFiles({
    cwd,
    policy,
    plugins,
    config: derived,
    ctx: await projectContext(cwd),
  });
  const typed =
    derived.gen === undefined
      ? []
      : await genFiles({
          cwd,
          config: derived,
          kinds: [],
          check: false,
          dryRun: true,
        });
  return [
    ...emitted.map((item) => `${item.path}\u0000${item.contents}`),
    ...typed.map((item) => `${item.rel}\u0000${item.text}`),
  ].toSorted();
}

function sameOutputs(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((item, index) => item === b[index]);
}

function pruned(
  config: PermDockConfig,
  entries: readonly ConfigDefault[],
): PermDockConfig {
  // SAFETY: PermDockConfig is a plain object; withoutPath only drops keys.
  let value = config as unknown as Record<string, unknown>;
  for (const entry of entries) {
    value = withoutPath(value, entry.path);
  }
  // SAFETY: removing optional keys keeps the PermDockConfig shape.
  return value as PermDockConfig;
}

/**
 * The entries whose removal keeps every generated byte. All of them first; on a
 * difference, each section, then each key of a section that differs.
 */
async function provenRemovals(
  entries: readonly ConfigDefault[],
  differs: (entries: readonly ConfigDefault[]) => Promise<boolean>,
): Promise<{
  readonly accepted: readonly ConfigDefault[];
  readonly refused: readonly ConfigDefault[];
}> {
  if (entries.length === 0 || !(await differs(entries))) {
    return { accepted: entries, refused: [] };
  }
  const sections = [...new Set(entries.map((entry) => entry.section))];
  const accepted: ConfigDefault[] = [];
  const refused: ConfigDefault[] = [];
  for (const section of sections) {
    const group = entries.filter((entry) => entry.section === section);
    if (!(await differs([...accepted, ...group]))) {
      accepted.push(...group);
      continue;
    }
    for (const entry of group) {
      if (await differs([...accepted, entry])) {
        refused.push(entry);
      } else {
        accepted.push(entry);
      }
    }
  }
  return { accepted, refused };
}

function propertyAt(
  root: Estree,
  path: readonly string[],
): { readonly object: Estree; readonly property: Estree } | undefined {
  let object = root;
  for (const [index, key] of path.entries()) {
    const property = nodes(object.properties).find(
      (item) => propertyKey(item) === key,
    );
    if (property === undefined) {
      return undefined;
    }
    if (index === path.length - 1) {
      return { object, property };
    }
    const value = child(property, "value");
    if (value?.type !== "ObjectExpression") {
      return undefined;
    }
    object = value;
  }
  return undefined;
}

/** `text` with each key removed, one per parse so ranges stay current. */
function removeKeys(
  file: string,
  text: string,
  paths: readonly (readonly string[])[],
): { readonly text: string; readonly unreachable: readonly string[] } {
  let source = text;
  const unreachable: string[] = [];
  for (const path of paths) {
    const parsed = parseSync(file, source, { sourceType: "module" });
    // SAFETY: Estree is an all-optional view of the Oxc program, whose nodes all carry `start` and `end`.
    const program = parsed.program as unknown as Estree;
    const roots = resolveConfigRoot(program, {
      isConfigFile: basename(file).startsWith("permdock.config."),
    }).roots;
    const found = roots
      .map((root) => propertyAt(root, path))
      .find((item) => item !== undefined);
    if (found === undefined) {
      unreachable.push(path.join("."));
      continue;
    }
    source = applyEditsStrict(source, [
      removeProperty(source, found.object, found.property),
    ]);
  }
  return { text: source, unreachable };
}

/**
 * `permdock codemod config --prune`: removes each config key set to its
 * default. It regenerates every output in memory with and without the keys and
 * writes nothing when a byte differs; such a key is reported and kept.
 */
export async function pruneConfig(options: {
  readonly cwd: string;
  readonly check: boolean;
  readonly dryRun: boolean;
  readonly force?: boolean;
}): Promise<PruneReport> {
  const file = configFileIn(options.cwd);
  if (file === undefined) {
    throw new CliError(
      "usage",
      "codemod config --prune: no permdock.config file",
      { code: "config_not_found" },
    );
  }
  const parsed = await readParsedConfig(options.cwd, file, { fresh: true });
  const entries = restatedDefaults(parsed.config);
  const baseline = await outputsOf(options.cwd, file, parsed.config);
  const { accepted, refused } = await provenRemovals(
    entries,
    async (some) =>
      !sameOutputs(
        baseline,
        await outputsOf(options.cwd, file, pruned(parsed.config, some)),
      ),
  );
  const text = readFileSync(file, "utf8");
  const edited = removeKeys(
    file,
    text,
    accepted.map((entry) => entry.path),
  );
  const removed = accepted
    .map((entry) => entry.path.join("."))
    .filter((key) => !edited.unreachable.includes(key));
  if (!options.check && !options.dryRun && edited.text !== text) {
    refuseDirty({
      command: "codemod",
      invocation: "codemod config --prune",
      cwd: options.cwd,
      paths: [file],
      force: options.force === true,
    });
    applyFiles(options.cwd, [{ path: file, text: edited.text }]);
  }
  return {
    file: rel(options.cwd, file),
    check: options.check,
    removed,
    kept: refused.map((entry) => ({
      key: entry.path.join("."),
      why: "removing it changes a generated file",
    })),
    unreachable: edited.unreachable,
  };
}

export async function runPruneConfig(options: {
  readonly cwd: string;
  readonly check: boolean;
  readonly dryRun: boolean;
  readonly force?: boolean;
  readonly json: boolean;
}): Promise<CommandResult> {
  const report = await pruneConfig(options);
  const code = options.check && report.removed.length > 0 ? 1 : 0;
  if (options.json) {
    return { code, output: JSON.stringify(report, null, 2), data: report };
  }
  const verb = options.check || options.dryRun ? "would remove" : "removed";
  const lines = [
    `permdock codemod config --prune: ${verb} ${String(report.removed.length)} ${report.removed.length === 1 ? "key" : "keys"} from ${report.file}`,
    ...report.removed.map((key) => `  ${key}`),
    ...report.kept.map((item) => `  kept ${item.key}: ${item.why}`),
    ...report.unreachable.map(
      (key) =>
        `  kept ${key}: not an object literal key the codemod can edit; remove it by hand`,
    ),
  ];
  return { code, output: lines.join("\n") };
}
