import { createHash } from "node:crypto";

import type { GenModel } from "./model.ts";

import { canonicalJson } from "../../core/canonical-json.ts";

/** What the header line of a generated module names. */
export type HeaderInfo = {
  /** The package version of the plugin that wrote the module. */
  readonly version: string;
  /** The policy module, relative to the project. */
  readonly policy: string;
  /** `sha-256:` digest of the model, base64url. */
  readonly hash: string;
};

/** The digest `--check` and doctor read to tell a stale file from a hand edit. */
export function modelDigest(model: GenModel): string {
  return createHash("sha256").update(canonicalJson(model)).digest("base64url");
}

/**
 * `// @generated by permdock generate zod@0.27.2 from policy.ts sha-256:…; do
 * not edit`.
 */
export function generatedHeader(kind: string, info: HeaderInfo): string {
  return `// @generated by permdock generate ${kind}@${info.version} from ${info.policy} sha-256:${info.hash}; do not edit`;
}
