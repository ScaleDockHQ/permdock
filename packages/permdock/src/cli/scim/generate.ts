import type { CommandResult } from "../core/result.ts";
import type { PermDockConfig, RlsDialect } from "../types.ts";

import { quoteSqlIdent } from "../../core/sql.ts";
import {
  SCIM_SCHEMA,
  SCIM_TABLES,
  SCIM_UNIQUE,
} from "../../scim/postgres-store.ts";
import { applyFiles, fileSummary } from "../core/files.ts";
import { STDOUT, driftOf } from "../core/output-files.ts";

const SCIM_MARKER = "-- generated by permdock scim generate";

/** The client roles each dialect's data API connects as; none may reach the directory. */
function clientRoles(dialect: RlsDialect): readonly string[] {
  switch (dialect) {
    case "supabase":
      return ["public", "anon", "authenticated"];
    case "neon":
      return ["public", "anonymous", "authenticated"];
    case "guc":
      return ["public"];
    default: {
      const exhaustive: never = dialect;
      return exhaustive;
    }
  }
}

/**
 * The directory `postgresDirectoryStore` reads and writes: users, groups and
 * group members keyed on `(tenant, id)`, with `userName` and `externalId`
 * unique per tenant. Member values are SCIM `value`s, not a foreign key to
 * users, because a member may be a nested group. No client role may read
 * or write the tables.
 */
export function scimSchemaSql(input: {
  readonly schema: string;
  readonly dialect: RlsDialect;
}): string {
  const schema = quoteSqlIdent(input.schema);
  const table = (name: string): string => `${schema}.${quoteSqlIdent(name)}`;
  const users = table(SCIM_TABLES.users);
  const groups = table(SCIM_TABLES.groups);
  const members = table(SCIM_TABLES.members);
  const all = [users, groups, members].join(", ");
  return `${SCIM_MARKER} (--dialect ${input.dialect})
-- the SCIM directory postgresDirectoryStore reads and writes for scimHandler; every row belongs to one tenant
create schema if not exists ${schema};

create table if not exists ${users} (
  seq bigint generated always as identity unique,
  tenant text not null check (tenant <> ''),
  id text not null check (id <> ''),
  user_name text not null,
  external_id text,
  active boolean not null default true,
  emails jsonb,
  x jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  revision bigint not null default 1,
  primary key (tenant, id),
  constraint ${quoteSqlIdent(SCIM_UNIQUE.userName)} unique (tenant, user_name),
  constraint ${quoteSqlIdent(SCIM_UNIQUE.userExternalId)} unique (tenant, external_id)
);

create table if not exists ${groups} (
  seq bigint generated always as identity unique,
  tenant text not null check (tenant <> ''),
  id text not null check (id <> ''),
  display_name text not null,
  external_id text,
  roles text[],
  x jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  revision bigint not null default 1,
  primary key (tenant, id),
  constraint ${quoteSqlIdent(SCIM_UNIQUE.groupExternalId)} unique (tenant, external_id)
);

create table if not exists ${members} (
  tenant text not null,
  group_id text not null,
  user_id text not null,
  position integer not null default 0,
  primary key (tenant, group_id, user_id),
  foreign key (tenant, group_id) references ${groups} (tenant, id) on delete cascade
);
create index if not exists ${quoteSqlIdent(`${SCIM_TABLES.members}_user_idx`)} on ${members} (tenant, user_id);

-- server only: grant select, insert, update and delete on these tables to the role postgresDirectoryStore
-- connects as when it does not own them
alter table ${users} enable row level security;
alter table ${groups} enable row level security;
alter table ${members} enable row level security;
revoke all on table ${all} from ${clientRoles(input.dialect).join(", ")};
`;
}

/** `supabase/schemas/<schema>/scim.sql` for Supabase, the pg-delta per-schema layout; `permdock_scim.sql` otherwise. */
function scimOut(dialect: RlsDialect, schema: string): string {
  return dialect === "supabase"
    ? `supabase/schemas/${schema}/scim.sql`
    : "permdock_scim.sql";
}

export function runScimGenerate(input: {
  readonly cwd: string;
  readonly config: PermDockConfig;
  readonly out?: string;
  readonly dialect?: RlsDialect;
  readonly schema?: string;
  readonly check: boolean;
  readonly dryRun: boolean;
}): CommandResult {
  const dialect = input.dialect ?? input.config.rls?.dialect ?? "supabase";
  const schema = input.schema ?? input.config.rls?.schema ?? SCIM_SCHEMA;
  const sql = scimSchemaSql({ schema, dialect });
  const out = input.out ?? scimOut(dialect, schema);
  const data = {
    out,
    dialect,
    schema,
    tables: Object.values(SCIM_TABLES).map((name) => `${schema}.${name}`),
  };
  if (out === STDOUT) {
    return { code: 0, output: sql.trimEnd(), data: { ...data, sql } };
  }
  if (input.check) {
    const drift = driftOf(input.cwd, [{ part: "scim", rel: out, text: sql }]);
    return drift.length === 0
      ? { code: 0, output: `${out} is current`, data }
      : {
          code: 1,
          output: `${drift.join("\n")}\nrun permdock scim generate`,
          data: { ...data, drift },
        };
  }
  const applied = applyFiles(input.cwd, [{ path: out, text: sql }], {
    dryRun: input.dryRun,
  });
  return {
    code: 0,
    output: fileSummary(applied, input.dryRun),
    data: { ...data, files: applied },
    next: [
      {
        when: "in CI, to fail when the file is stale",
        command: "permdock scim generate --check",
      },
    ],
  };
}
