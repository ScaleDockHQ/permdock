/** A trigger `rls generate` writes on a table of the application. */
export type GeneratedTrigger = {
  readonly name: string;
  /** `schema.table` as written in the SQL. */
  readonly table: string;
  /** The option that asks for it, and how to leave it out. */
  readonly reason: string;
};

const CREATE =
  /^create trigger\s+("[^"]+"|[\w$]+)[^;]*?\bon\s+("[^"]+"(?:\."[^"]+")?|[\w$.]+)/gmu;

function unquote(name: string): string {
  return name.replaceAll('"', "");
}

function reasonOf(name: string): string {
  if (name === "permdock_custom_role_name_guard") {
    return "customRoleWrites.roles: a tenant role cannot take a declared or shared role's name";
  }
  if (name === "permdock_custom_role_cascade") {
    return "customRoleWrites.roles: a rename or delete of a role carries its grants";
  }
  if (name.startsWith("permdock_sync_custom_role")) {
    return "customRoles.from.sync: each write to the legacy table rebuilds the role's grants";
  }
  if (
    name.startsWith("permdock_holders") ||
    name.startsWith("permdock_transfer_only")
  ) {
    return "ownershipTriggers; set rls.ownershipTriggers.<scope>: false to skip";
  }
  if (name === "permdock_assignment") {
    return "assignments: a role assignment is checked against the caller's own roles";
  }
  if (name.startsWith("permdock_closure")) {
    return "the relationship closure table follows its source table";
  }
  return "generated by rls generate";
}

/** The triggers `sql` creates, in order, each with the option behind it. */
export function generatedTriggers(sql: string): readonly GeneratedTrigger[] {
  const found: GeneratedTrigger[] = [];
  for (const match of sql.matchAll(CREATE)) {
    const name = unquote(match[1] ?? "");
    const table = unquote(match[2] ?? "");
    if (name !== "" && table !== "") {
      found.push({ name, table, reason: reasonOf(name) });
    }
  }
  return found;
}

/** One generate note per trigger. */
export function triggerNotes(sql: string): readonly string[] {
  return generatedTriggers(sql).map(
    (trigger) =>
      `generated trigger ${trigger.name} on ${trigger.table} (${trigger.reason})`,
  );
}
