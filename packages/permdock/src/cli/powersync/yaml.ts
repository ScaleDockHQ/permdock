import type { PowerSyncPlan } from "./streams.ts";

import { RECONNECT_DOCS } from "./claims.ts";

/**
 * A YAML scalar quoted as oxfmt and Prettier write it: single quotes around a
 * `"`, unless a backslash needs a double-quoted escape.
 */
function yamlString(text: string): string {
  return text.includes('"') && !text.includes("\\")
    ? `'${text.replaceAll("'", "''")}'`
    : JSON.stringify(text);
}

/**
 * `sync-config.yaml`: edition 3 Sync Streams, one auto-subscribed stream per
 * synced resource.
 */
export function powersyncYaml(plan: PowerSyncPlan): string {
  const lines = [
    "# Generated by permdock powersync generate from the policy. Do not edit.",
    ...(plan.publication === undefined
      ? []
      : [
          "# Tables outside public must be in the powersync publication:",
          `# ${plan.publication}`,
        ]),
    ...(plan.streams.some((stream) => stream.claims.length > 0)
      ? [
          "# Streams that read token claims keep the claims a connection started with:",
          "# refresh the session and reconnect PowerSync after a role or tenant change.",
          `# https://permdock.com${RECONNECT_DOCS}`,
          ...plan.streams
            .filter((stream) => stream.claims.length > 0)
            .map(
              (stream) =>
                `#   ${stream.name} reads ${stream.claims.join(", ")}`,
            ),
        ]
      : []),
    "config:",
    "  edition: 3",
    "",
    "streams:",
  ];
  if (
    plan.streams.length === 0 &&
    plan.subject.length === 0 &&
    plan.tables.length === 0
  ) {
    lines[lines.length - 1] = "streams: {}";
  }
  for (const stream of [...plan.streams, ...plan.subject, ...plan.tables]) {
    lines.push(
      `  ${stream.name}:`,
      "    auto_subscribe: true",
      "    queries:",
      ...stream.queries.map((query) => `      - ${yamlString(query)}`),
    );
  }
  for (const item of plan.omitted) {
    lines.push(`# ${item.resource}: not synced, ${item.reason}`);
  }
  return `${lines.join("\n")}\n`;
}
