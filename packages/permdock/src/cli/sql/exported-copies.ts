import { readFileSync } from "node:fs";
import { relative } from "node:path";

import type { SqlNode } from "./ast.ts";

import { isRecord } from "../../core/compact.ts";
import { sqlFiles } from "../files.ts";
import {
  SqlSyntaxError,
  parseSqlFile,
  readRelation,
  removeStatements,
  stringValues,
} from "./ast.ts";

/**
 * Root folders of a pg-delta export PermDock never writes into or rewrites:
 * `_custom` holds hand-written SQL and `_cluster` the cluster-level objects.
 */
export const RESERVED_EXPORT_DIRS: ReadonlySet<string> = new Set([
  "_custom",
  "_cluster",
]);

const ROUTINES: ReadonlySet<string> = new Set([
  "OBJECT_FUNCTION",
  "OBJECT_PROCEDURE",
  "OBJECT_ROUTINE",
]);

/** A SQL file, `path` relative to the project. */
export type SqlText = { readonly path: string; readonly text: string };

/** Whether PermDock wrote `text`: its first line is a PermDock header. */
export function generatedByPermdock(text: string): boolean {
  return (
    text.startsWith("-- generated by permdock") ||
    text.startsWith("-- permdock:")
  );
}

/** Whether `path` sits in a reserved export folder directly under `schemaDir`. */
export function inReservedDir(schemaDir: string, path: string): boolean {
  const first = relative(schemaDir, path).split(/[\\/]/u)[0] ?? "";
  return RESERVED_EXPORT_DIRS.has(first.toLowerCase());
}

function routineKey(names: readonly string[]): string | undefined {
  const [schema, name] =
    names.length === 1 ? ["public", names[0]] : names.slice(-2);
  return name === undefined ? undefined : `function:${schema}.${name}`;
}

function objectNames(object: unknown): readonly string[] {
  const routine: unknown = isRecord(object)
    ? (object["ObjectWithArgs"] ?? object)
    : undefined;
  return isRecord(routine) ? stringValues(routine["objname"]) : [];
}

function policyKey(
  schema: string | undefined,
  table: string,
  name: string,
): string {
  return `policy:${schema ?? "public"}.${table}\0${name}`;
}

/** The PermDock-relevant objects one statement creates or alters. */
function statementKeys(statement: SqlNode): readonly string[] {
  const { node } = statement;
  switch (statement.kind) {
    case "CreateFunctionStmt": {
      const key = routineKey(stringValues(node["funcname"]));
      return key === undefined ? [] : [key];
    }
    case "CreatePolicyStmt": {
      const table = readRelation(node["table"]);
      const name = node["policy_name"];
      return table === undefined || typeof name !== "string"
        ? []
        : [policyKey(table.schema, table.name, name)];
    }
    case "AlterFunctionStmt": {
      const key = routineKey(objectNames(node["func"]));
      return key === undefined ? [] : [key];
    }
    case "AlterOwnerStmt":
    case "CommentStmt": {
      const type = node["objectType"] ?? node["objtype"];
      if (type === "OBJECT_POLICY") {
        const object: unknown = node["object"];
        const list: unknown = isRecord(object) ? object["List"] : undefined;
        const names = stringValues(isRecord(list) ? list["items"] : undefined);
        const [table, name] = names.slice(-2);
        return table === undefined || name === undefined || names.length < 2
          ? []
          : [policyKey(names.length === 3 ? names[0] : undefined, table, name)];
      }
      if (typeof type !== "string" || !ROUTINES.has(type)) {
        return [];
      }
      const key = routineKey(objectNames(node["object"]));
      return key === undefined ? [] : [key];
    }
    case "GrantStmt": {
      const type = node["objtype"];
      if (typeof type !== "string" || !ROUTINES.has(type)) {
        return [];
      }
      const objects: unknown = node["objects"];
      return (Array.isArray(objects) ? objects : []).flatMap(
        (object: unknown) => {
          const key = routineKey(objectNames(object));
          return key === undefined ? [] : [key];
        },
      );
    }
    default:
      return [];
  }
}

async function parsed(text: string): Promise<readonly SqlNode[] | undefined> {
  try {
    return await parseSqlFile(text);
  } catch (error) {
    if (error instanceof SqlSyntaxError) {
      return undefined;
    }
    throw error;
  }
}

/** The functions and policies `texts` create, as statement keys. */
export async function ownedObjects(
  texts: readonly string[],
): Promise<ReadonlySet<string>> {
  const owned = new Set<string>();
  for (const text of texts) {
    for (const statement of (await parsed(text)) ?? []) {
      if (
        statement.kind === "CreateFunctionStmt" ||
        statement.kind === "CreatePolicyStmt"
      ) {
        for (const key of statementKeys(statement)) {
          owned.add(key);
        }
      }
    }
  }
  return owned;
}

/**
 * `function:permdock.f` as `permdock.f`, `policy:public.t\0p` as `p on
 * public.t`.
 */
export function shownKey(key: string): string {
  const [kind, rest = ""] = key.split(":", 2);
  if (kind !== "policy") {
    return rest;
  }
  const [table = "", name = ""] = rest.split("\0");
  return `${name} on ${table}`;
}

/**
 * The SQL files under `schemaDir` PermDock did not write, outside the reserved
 * export folders and `own`.
 */
export function foreignSchemaFiles(
  cwd: string,
  schemaDir: string,
  own: ReadonlySet<string>,
): readonly SqlText[] {
  return sqlFiles(cwd, [schemaDir]).flatMap((file) => {
    const path = relative(cwd, file).split(/[\\/]/u).join("/");
    if (own.has(path) || inReservedDir(schemaDir, path)) {
      return [];
    }
    const text = readFileSync(file, "utf8");
    return generatedByPermdock(text) ? [] : [{ path, text }];
  });
}

/**
 * `text` without its copies of the objects in `owned`, and the objects it
 * created. An owner, comment or grant statement goes only with a `create` of
 * the same object in this file: a grant on a PermDock function in a file of the
 * app's own is the app's decision. A file that does not parse stays.
 */
export async function withoutOwned(
  text: string,
  owned: ReadonlySet<string>,
): Promise<{ readonly text: string; readonly removed: readonly string[] }> {
  const statements = (await parsed(text)) ?? [];
  const removed = new Set<string>();
  for (const statement of statements) {
    if (
      statement.kind === "CreateFunctionStmt" ||
      statement.kind === "CreatePolicyStmt"
    ) {
      for (const key of statementKeys(statement)) {
        if (owned.has(key)) {
          removed.add(key);
        }
      }
    }
  }
  if (removed.size === 0) {
    return { text, removed: [] };
  }
  const next = removeStatements(text, statements, (statement) => {
    const keys = statementKeys(statement);
    return keys.length > 0 && keys.every((key) => removed.has(key));
  });
  return { text: next, removed: [...removed] };
}
