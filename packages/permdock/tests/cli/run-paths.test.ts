import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { run } from "../../src/cli/core/run.ts";
import { rlsGenerate } from "./rls-call.ts";

const FIXTURE = join(import.meta.dirname, "fixtures/mini-app");

function capture(env: Readonly<Record<string, string>> = {}): {
  readonly env: Readonly<Record<string, string>>;
  readonly stdout: () => void;
  readonly stderr: () => void;
} {
  return { env, stdout: () => undefined, stderr: () => undefined };
}

/** The error document a failed `--json` run prints as one line on stderr. */
function errorOf(stderr: string): unknown {
  const parsed: unknown = JSON.parse(stderr);
  return parsed;
}

describe("run plugins option", () => {
  it("uses the plugins passed to run instead of the config file", async () => {
    const result = await run(["generate", "--no-cache"], {
      cwd: FIXTURE,
      plugins: [],
    });
    expect(result.code).toBe(0);
    expect(result.stderr).toContain("Generated 0 files");
  });
});

describe("removed generate commands", () => {
  it.each([
    [["powersync", "generate"], "generate --only powersync"],
    [["openapi", "emit"], "generate --only openapi"],
    [["gen"], "generate"],
    [["scim"], "generate --only scim"],
    [["scim", "generate"], "generate --only scim"],
    [["supabase", "hook"], "generate --only supabaseHook"],
    [["supabase", "hook", "generate"], "generate --only supabaseHook"],
  ])("points %j at %s", async (argv, hint) => {
    const result = await run(argv, { cwd: FIXTURE });
    expect(result.code).toBe(2);
    expect(result.stderr).toContain(hint);
  });
});

describe("run: groups", () => {
  it("asks for a subcommand when a group gets only flags", async () => {
    const result = await run(["openapi", "--check", "--json"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(2);
    expect(errorOf(result.stderr)).toMatchObject({ reason: "usage" });
  });

  it("lists a bare group's subcommands as choices under --json", async () => {
    const result = await run(["rls", "--json"], { cwd: FIXTURE });
    expect(result.code).toBe(2);
    expect(errorOf(result.stderr)).toMatchObject({
      reason: "usage",
      data: {
        choices: { "<command>": ["import", "verify", "migrate", "explain"] },
      },
    });
  });

  it("prints the catalog for --out -", async () => {
    const result = await run(["catalog", "--out", "-", "--no-json"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(0);
    expect(result.stdout).toMatch(/^\{\n {2}"\$schema"/u);
  });

  it("keeps rls generate's stdout to the SQL for --out -", async () => {
    const result = await rlsGenerate(["--out", "-", "--no-json"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(0);
    expect(result.stdout).toMatch(/^-- generated by permdock rls generate/u);
  });

  it("refuses --out - where the command writes only files", async () => {
    const result = await run(["collect", "--out", "-", "--json"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(2);
    expect(errorOf(result.stderr)).toMatchObject({
      reason: "invalid_value",
      data: { flag: "--out" },
    });
  });

  it("prints a group's help as text", async () => {
    const result = await run(["rls", "--help"], { cwd: FIXTURE });
    expect(result.code).toBe(0);
    expect(result.stdout).toMatch(/^permdock rls: /u);
  });
});

describe("run: the root", () => {
  it.each([
    [["--json"], "usage", "permdock needs a command"],
    [
      ["--format", "xml", "--json"],
      "invalid_value",
      "--format 'xml' is not one of text, json, github, sarif.",
    ],
    [
      ["--json", "--format", "text"],
      "invalid_value",
      "--json and --format text ask for different output; pick one",
    ],
    [
      ["rls", "--format", "xml", "--json"],
      "invalid_value",
      "--format 'xml' is not one of text, json, github, sarif.",
    ],
  ])("answers %j with %s", async (argv, reason, message) => {
    const result = await run(argv, { cwd: FIXTURE });
    expect(result.code).toBe(2);
    expect(errorOf(result.stderr)).toMatchObject({ reason, message });
  });
});

describe("run: flags", () => {
  it("answers a flag removed before 0.10 as an unknown flag", async () => {
    const result = await run(["scan", "--legacy", "--json"], { cwd: FIXTURE });
    expect(errorOf(result.stderr)).toMatchObject({ reason: "unknown_flag" });
  });

  it("refuses --json with another --format", async () => {
    const result = await run(["doctor", "--json", "--format", "text"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(2);
    expect(errorOf(result.stderr)).toMatchObject({ reason: "invalid_value" });
  });

  it("repeats --cwd and --config in the command consent asks for", async () => {
    const result = await run(
      [
        "codemod",
        "0.26",
        "--agent",
        "yes",
        "--cwd",
        FIXTURE,
        "--config",
        "permdock.config.ts",
      ],
      { cwd: FIXTURE },
    );
    expect(result.code).toBe(2);
    expect(result.stderr).toContain(
      `--cwd ${FIXTURE} --config permdock.config.ts --yes --effects-digest `,
    );
  });
});

describe("run: output formats", () => {
  it("prints no annotations and an empty SARIF run for a report without findings", async () => {
    const github = await run(["config", "--format", "github"], {
      cwd: FIXTURE,
      io: capture(),
    });
    expect(github.stdout).toBe("");
    const sarif = await run(["config", "--format", "sarif"], {
      cwd: FIXTURE,
      io: capture(),
    });
    expect(JSON.parse(sarif.stdout)).toMatchObject({
      version: "2.1.0",
      runs: [{ results: [] }],
    });
  });

  it("refuses --format github for a command that reports no findings", async () => {
    const result = await run(["preset", "url", "--format", "github"], {
      cwd: FIXTURE,
    });
    expect(result.code).toBe(2);
    expect(result.stderr).toContain(
      "--format github renders findings, and permdock preset url reports none; use text or json",
    );
  });
});

describe("run: --debug", () => {
  it("logs the mode, the config file and the exit code", async () => {
    const result = await run(["config", "--debug"], {
      cwd: FIXTURE,
      io: { ...capture(), errColor: true },
    });
    expect(result.code).toBe(0);
    expect(result.stderr).toContain("debug: config: agent mode off");
    expect(result.stderr).toContain(
      `debug: config file: ${join(FIXTURE, "permdock.config.ts")}`,
    );
    expect(result.stderr).toContain("debug: config: exit 0");
  });

  it("logs the cause of a network error", async () => {
    const result = await run(["cloud", "pull", "--project", "p", "--debug"], {
      cwd: FIXTURE,
      io: {
        ...capture({ PERMDOCK_CLOUD_TOKEN: "pdt_test" }),
        fetch: () => Promise.reject(new Error("connect ECONNREFUSED")),
      },
    });
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("cause: connect ECONNREFUSED");
    expect(result.stderr).not.toContain("pdt_test");
  });
});
