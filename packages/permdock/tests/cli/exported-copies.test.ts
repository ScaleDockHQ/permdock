import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { exportedDuplicates } from "../../src/cli/doctor/exported-duplicates.ts";
import { exportedCopyFiles } from "../../src/cli/generate/exported-copies.ts";
import { withoutOwned } from "../../src/cli/sql/exported-copies.ts";

const TMP = join(import.meta.dirname, "../../tmp");
const temps: string[] = [];

const HELPERS = `-- generated by permdock rls generate
create or replace function "permdock".permdock_user_id()
returns uuid language sql stable as $$ select auth.uid() $$;
create policy "permdock_jobs_read" on "public"."jobs" for select to authenticated using (true);
`;

const EXPORTED_FUNCTION = `CREATE FUNCTION permdock.permdock_user_id() RETURNS uuid
    LANGUAGE sql STABLE
    AS $$ select auth.uid() $$;

ALTER FUNCTION permdock.permdock_user_id() OWNER TO postgres;

COMMENT ON FUNCTION permdock.permdock_user_id() IS 'subject';

REVOKE ALL ON FUNCTION permdock.permdock_user_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION permdock.permdock_user_id() TO authenticated;
`;

const EXPORTED_TABLE = `CREATE TABLE public.jobs (id uuid NOT NULL);

ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "permdock_jobs_read" ON public.jobs FOR SELECT TO authenticated USING (true);

COMMENT ON POLICY "permdock_jobs_read" ON public.jobs IS 'read';

CREATE POLICY "own_rows" ON public.jobs FOR SELECT TO authenticated USING (true);
`;

function project(files: Readonly<Record<string, string>>): string {
  mkdirSync(TMP, { recursive: true });
  const dir = mkdtempSync(join(TMP, "exported-copies-"));
  temps.push(dir);
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
  }
  return dir;
}

const HELPERS_FILE = {
  plugin: "rls",
  path: "supabase/schemas/permdock/helpers.sql",
  contents: HELPERS,
};
const EMITTED = [HELPERS_FILE];

describe(withoutOwned, () => {
  it("drops the copy with its owner, comment and grants, and keeps the rest", async () => {
    const owned = new Set([
      "function:permdock.permdock_user_id",
      "policy:public.jobs\0permdock_jobs_read",
    ]);
    const fn = await withoutOwned(EXPORTED_FUNCTION, owned);
    expect(fn.text.trim()).toBe("");
    expect(fn.removed).toStrictEqual(["function:permdock.permdock_user_id"]);
    const table = await withoutOwned(EXPORTED_TABLE, owned);
    expect(table.text).toContain("CREATE TABLE public.jobs");
    expect(table.text).toContain('CREATE POLICY "own_rows"');
    expect(table.text).not.toContain("permdock_jobs_read");
  });

  it("keeps a grant on a PermDock function in a file without its create", async () => {
    const grant =
      "GRANT EXECUTE ON FUNCTION permdock.permdock_user_id() TO service_role;\n";
    expect(
      await withoutOwned(
        grant,
        new Set(["function:permdock.permdock_user_id"]),
      ),
    ).toStrictEqual({ text: grant, removed: [] });
  });
});

describe(exportedCopyFiles, () => {
  afterEach(() => {
    for (const dir of temps.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("rewrites the exported files without the objects the plugins emit", async () => {
    const cwd = project({
      "supabase/schemas/permdock/functions/permdock_user_id.sql":
        EXPORTED_FUNCTION,
      "supabase/schemas/public/tables/jobs.sql": EXPORTED_TABLE,
      "supabase/schemas/_custom/jobs.sql": EXPORTED_TABLE,
    });
    const result = await exportedCopyFiles(cwd, {}, EMITTED);
    expect(result.files.map((file) => file.path)).toStrictEqual([
      "supabase/schemas/permdock/functions/permdock_user_id.sql",
      "supabase/schemas/public/tables/jobs.sql",
    ]);
    expect(result.notes).toStrictEqual([
      "removed the exported copy of permdock.permdock_user_id from supabase/schemas/permdock/functions/permdock_user_id.sql",
      "removed the exported copy of permdock_jobs_read on public.jobs from supabase/schemas/public/tables/jobs.sql",
    ]);
  });

  it("leaves a migrations project alone", async () => {
    const cwd = project({
      "supabase/schemas/public/tables/jobs.sql": EXPORTED_TABLE,
    });
    expect(
      await exportedCopyFiles(
        cwd,
        { supabase: { schemas: "migrations" } },
        EMITTED,
      ),
    ).toStrictEqual({ files: [], notes: [] });
  });

  it("refuses to write into a reserved export folder", async () => {
    const cwd = project({});
    await expect(
      exportedCopyFiles(cwd, {}, [
        { ...HELPERS_FILE, path: "supabase/schemas/_custom/permdock.sql" },
      ]),
    ).rejects.toThrow(
      /_custom\/ and _cluster\/ belong to the pg-delta export/u,
    );
  });
});

describe(exportedDuplicates, () => {
  it("names both files of each duplicate", async () => {
    const findings = await exportedDuplicates("supabase/schemas", [
      { path: "supabase/schemas/permdock/helpers.sql", text: HELPERS },
      { path: "supabase/schemas/public/tables/jobs.sql", text: EXPORTED_TABLE },
      { path: "supabase/schemas/_custom/jobs.sql", text: EXPORTED_TABLE },
    ]);
    expect(findings.map((finding) => finding.message)).toStrictEqual([
      "supabase/schemas/public/tables/jobs.sql and supabase/schemas/permdock/helpers.sql both create permdock_jobs_read on public.jobs",
    ]);
  });
});
