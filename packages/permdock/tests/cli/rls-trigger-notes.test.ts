import { describe, expect, it } from "vitest";

import {
  generatedTriggers,
  triggerNotes,
} from "../../src/cli/rls/trigger-notes.ts";

const SQL = `drop trigger if exists "permdock_custom_role_name_guard" on "public"."app_roles";
create trigger "permdock_custom_role_name_guard"
  before insert or update on "public"."app_roles"
  for each row execute function "permdock".permdock_custom_role_name_guard();
create trigger permdock_holders_org after insert on public.user_roles
  for each row execute function f();
create trigger "other" after insert on t for each row execute function f();`;

describe("generatedTriggers", () => {
  it("names each trigger, its table and the option behind it", () => {
    expect(generatedTriggers(SQL)).toEqual([
      {
        name: "permdock_custom_role_name_guard",
        table: "public.app_roles",
        reason:
          "customRoleWrites.roles: a tenant role cannot take a declared or shared role's name",
      },
      {
        name: "permdock_holders_org",
        table: "public.user_roles",
        reason:
          "ownershipTriggers; set rls.ownershipTriggers.<scope>: false to skip",
      },
      { name: "other", table: "t", reason: "generated by rls generate" },
    ]);
  });

  it("prints one note per trigger", () => {
    expect(triggerNotes(SQL)[1]).toBe(
      "generated trigger permdock_holders_org on public.user_roles (ownershipTriggers; set rls.ownershipTriggers.<scope>: false to skip)",
    );
  });
});
