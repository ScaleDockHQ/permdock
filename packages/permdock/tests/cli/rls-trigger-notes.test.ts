import { describe, expect, it } from "vitest";

import {
  generatedTriggers,
  triggerNotes,
} from "../../src/cli/rls/trigger-notes.ts";

const SQL = `drop trigger if exists "permdock_custom_role_name_guard" on "public"."app_roles";
create trigger "permdock_custom_role_name_guard"
  before insert or update on "public"."app_roles"
  for each row execute function "permdock".permdock_custom_role_name_guard();
create trigger permdock_holders_org after insert on public.user_roles
  for each row execute function f();
create trigger "other" after insert on t for each row execute function f();
create trigger "permdock_sync_custom_role_permissions" after insert on public.role_permissions for each row execute function f();
create trigger "permdock_sync_custom_role_guard_permissions" before insert on public.role_permissions for each row execute function f();`;

describe(generatedTriggers, () => {
  it("names each trigger, its table and the option behind it", () => {
    expect(generatedTriggers(SQL)).toStrictEqual([
      {
        name: "permdock_custom_role_name_guard",
        table: "public.app_roles",
        reason:
          "customRoleWrites.roles: a tenant role cannot take a declared or shared role's name",
      },
      {
        name: "permdock_holders_org",
        table: "public.user_roles",
        reason:
          "ownershipTriggers; set rls.ownershipTriggers.<scope>: false to skip",
      },
      { name: "other", table: "t", reason: "generated by rls generate" },
      {
        name: "permdock_sync_custom_role_permissions",
        table: "public.role_permissions",
        reason:
          "customRoles.from.sync: each write to the legacy table rebuilds the role's grants",
      },
      {
        name: "permdock_sync_custom_role_guard_permissions",
        table: "public.role_permissions",
        reason:
          "customRoles.from.sync: a signed-in caller writes only entries they may hand out",
      },
    ]);
  });

  it("prints one note per trigger", () => {
    expect(triggerNotes(SQL)[1]).toBe(
      "generated trigger permdock_holders_org on public.user_roles (ownershipTriggers; set rls.ownershipTriggers.<scope>: false to skip)",
    );
  });

  it("reads create or replace trigger and skips a trigger inside a function body", () => {
    const sql = `create or replace trigger permdock_assignment before insert on public.user_roles
  for each row execute function f();
create function g() returns void language plpgsql as $$
begin
  execute 'select 1';
end
$$;
create function h() returns text language sql as $body$
select 'x';
create trigger permdock_closure_fake after insert on public.nope for each row execute function f();
$body$;`;
    expect(generatedTriggers(sql)).toStrictEqual([
      {
        name: "permdock_assignment",
        table: "public.user_roles",
        reason:
          "assignments: a role assignment is checked against the caller's own roles",
      },
    ]);
  });
});
