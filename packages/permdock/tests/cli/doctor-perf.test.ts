import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import type { DoctorFinding } from "../../src/cli/shared/doctor-types.ts";
import type { PermDockConfig } from "../../src/cli/types.ts";

import { pd111 } from "../../src/cli/doctor/perf-limit.ts";
import {
  pd103,
  pd104,
  pd105,
  pd106,
  pd107,
  pd108,
} from "../../src/cli/doctor/perf-sql.ts";
import {
  TOKEN_CHARS_BUDGET,
  pd109,
  pd110,
  tokenChars,
} from "../../src/cli/doctor/perf-token.ts";
import { nodeFiles } from "../../src/cli/shared/doctor-files.ts";

const dirs: string[] = [];

function project(files: Readonly<Record<string, string>>): string {
  const cwd = mkdtempSync(join(tmpdir(), "permdock-perf-"));
  dirs.push(cwd);
  for (const [path, text] of Object.entries(files)) {
    const abs = join(cwd, path);
    mkdirSync(join(abs, ".."), { recursive: true });
    writeFileSync(abs, text);
  }
  return cwd;
}

function targets(findings: readonly DoctorFinding[]): readonly string[] {
  return findings.map((finding) => finding.target ?? "");
}

const NONE: PermDockConfig = {};

describe("doctor performance checks", () => {
  afterEach(() => {
    for (const dir of dirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  describe("PD103 per-row PermDock call in a policy", () => {
    it("flags the row helper and a can_ call on a row column, not a constant call", () => {
      const cwd = project({
        "supabase/schemas/jobs.sql": `
create policy jobs_read on public.jobs for select to authenticated
  using (permdock.permitted_jobs_row(jobs, 'jobs.read'));
create policy notes_read on public.notes for select
  using (permdock.can_note(notes.id, 'note.read'));
create policy flag_read on public.flags for select
  using (permdock.can_flag('x', 'flag.read') and (select auth.uid()) is not null);
create policy set_read on public.docs for select
  using (org_id = any ((select permdock.permitted_org_id_array('doc.read'))));
`,
      });
      const findings = pd103(cwd, NONE, nodeFiles);
      expect(targets(findings)).toStrictEqual([
        "supabase/schemas/jobs.sql:public.jobs:jobs_read",
        "supabase/schemas/jobs.sql:public.notes:notes_read",
      ]);
      expect(findings[0]?.code).toBe("PD103");
      expect(findings[0]?.severity).toBe("warning");
    });

    it("reads generated files too, so a stale output is reported", () => {
      const cwd = project({
        "supabase/schemas/permdock/policies.sql": `-- generated by permdock
create policy x on public.t for select using (permdock.permitted_t_row(t, 'k'));
`,
      });
      expect(pd103(cwd, NONE, nodeFiles)).toHaveLength(1);
    });
  });

  describe("PD104 multiple permissive policies", () => {
    it("flags two permissive policies for one command when the app wrote one", () => {
      const cwd = project({
        "supabase/schemas/permdock/p.sql": `-- generated by permdock
create policy a_select on public.t for select using (true);
`,
        "supabase/schemas/t.sql": `
create policy mine on public.t for all using (true);
create policy other_select on public.u for select using (true);
create policy other_restrict on public.u as restrictive for select using (true);
`,
      });
      const findings = pd104(cwd, NONE, nodeFiles);
      expect(targets(findings)).toStrictEqual(["public.t:select"]);
      expect(findings[0]?.message).toContain("a_select");
      expect(findings[0]?.message).toContain("mine");
    });

    it("leaves generated per-role policies alone", () => {
      const cwd = project({
        "supabase/schemas/permdock/p.sql": `-- generated by permdock
create policy a on public.t for select using (true);
create policy b on public.t for select using (true);
`,
      });
      expect(pd104(cwd, NONE, nodeFiles)).toStrictEqual([]);
    });
  });

  describe("PD105 unindexed follows, parent and walk columns", () => {
    const config: PermDockConfig = {
      rls: {
        tables: {
          job: { table: "jobs", follows: { job_parties: "job_id" } },
          employee: { table: "employees", walk: "recursive", user: "user_id" },
        },
      },
    };

    it("flags a column with no leading index", () => {
      const cwd = project({
        "supabase/schemas/idx.sql": `
create index on public.job_parties (job_id);
create index emp_x on public.employees (name, user_id);
`,
      });
      expect(targets(pd105(cwd, config, nodeFiles))).toStrictEqual([
        "public.employees.user_id",
      ]);
    });

    it("passes when every column leads an index", () => {
      const cwd = project({
        "supabase/schemas/permdock/indexes.sql": `-- generated by permdock
create index a on public.job_parties using btree ("job_id");
create index b on public.employees (user_id, id);
`,
      });
      expect(pd105(cwd, config, nodeFiles)).toStrictEqual([]);
    });
  });

  describe("PD106 text cast on an indexed key", () => {
    it("flags id::text compared in a policy or a function", () => {
      const cwd = project({
        "supabase/schemas/a.sql": `
create policy p on public.t for select using (t.id::text = any (select permdock.keys()));
create function public.f() returns void language plpgsql as $$
begin
  delete from public.folders where "parentId"::text = 'x';
  perform 1 where (select auth.uid())::text = 'y';
end $$;
create policy ok on public.t for select using (owner_id = (select auth.uid()));
`,
      });
      expect(targets(pd106(cwd, NONE, nodeFiles))).toStrictEqual([
        "supabase/schemas/a.sql:2",
        "supabase/schemas/a.sql:5",
      ]);
    });
  });

  describe("PD107 unsargable custom-role probe", () => {
    it("flags a tenant_id text cast or is not distinct from near custom roles", () => {
      const cwd = project({
        "supabase/schemas/b.sql": `
create function permdock.keys(p_tenant text) returns setof text language sql as $$
  select permission from permdock.custom_role_permissions
  where case when scope = 'tenant' then tenant_id::text = p_tenant else true end
$$;
create function permdock.other() returns setof uuid language sql as $$
  select id from permdock.custom_role_permissions where tenant_id is not distinct from null
$$;
create function permdock.fine() returns setof uuid language sql as $$
  select id from permdock.custom_role_permissions where tenant_id = p_tenant::uuid
$$;
create function public.unrelated() returns void language sql as $$
  select 1 from public.items where tenant_id::text = 'x'
$$;
`,
      });
      expect(targets(pd107(cwd, NONE, nodeFiles))).toStrictEqual([
        "supabase/schemas/b.sql:2",
        "supabase/schemas/b.sql:6",
      ]);
    });
  });

  describe("PD108 _rows(p) without a tenant lead", () => {
    it("flags a one-argument set call that no tenant predicate leads", () => {
      const cwd = project({
        "supabase/schemas/c.sql": `
create policy a on public.docs for select
  using (id in (select permdock.permitted_doc_rows('doc.read')));
create policy b on public.docs for select
  using (org_id = any ((select permdock.permitted_org_id_array('doc.read'))) and id in (select permdock.permitted_doc_rows('doc.read')));
create policy c on public.docs for select
  using (id in (select permdock.permitted_doc_rows('doc.read', org_id)));
`,
      });
      expect(targets(pd108(cwd, NONE, nodeFiles))).toStrictEqual([
        "supabase/schemas/c.sql:public.docs:a",
      ]);
    });
  });

  describe("PD109 jwt-mode custom roles", () => {
    it("errors on jwt mode with custom roles and no claims function", () => {
      const findings = pd109({
        rls: { authorize: "jwt", customRoles: true },
        supabase: { hook: {} },
      });
      expect(findings).toHaveLength(1);
      expect(findings[0]?.severity).toBe("error");
      expect(findings[0]?.code).toBe("PD109");
    });

    it("accepts database mode, no custom roles, and a hook that writes its own claims", () => {
      expect(
        pd109({ rls: { authorize: "database", customRoles: true } }),
      ).toStrictEqual([]);
      expect(pd109({ rls: { authorize: "jwt" } })).toStrictEqual([]);
      expect(
        pd109({
          rls: { authorize: "jwt", customRoles: true },
          supabase: { hook: { claims: { grants: "public.grants_claim" } } },
        }),
      ).toStrictEqual([]);
    });
  });

  describe("PD110 whole-token size", () => {
    it("measures the token the way the bench does", () => {
      expect(tokenChars({})).toBeGreaterThan(700);
      expect(
        tokenChars({ memberships: [{ id: "x".repeat(3_000) }] }),
      ).toBeGreaterThan(TOKEN_CHARS_BUDGET);
    });

    it("flags a hook sample whose token is over the budget", async () => {
      const big = { memberships: [{ id: "x".repeat(3_000) }] };
      const queries: string[] = [];
      const findings = await pd110(
        {
          cwd: "/",
          config: { supabase: { hook: {} } },
          files: nodeFiles,
          database: {
            url: "postgres://x",
            connect: () =>
              Promise.resolve({
                query: (sql: string) => {
                  queries.push(sql);
                  return Promise.resolve({
                    rows: sql.includes("custom_access_token_hook")
                      ? [{ claims: big }]
                      : [],
                  });
                },
                end: () => Promise.resolve(),
              }),
          },
        },
        [{ label: "a user with no rows", event: { user_id: "u" } }],
      );
      expect(findings).toHaveLength(1);
      expect(findings[0]?.code).toBe("PD110");
      expect(findings[0]?.message).toContain("a user with no rows");
      expect(queries).toContain("begin");
      expect(queries).toContain("rollback");
    });
  });

  describe("PD111 optional limit on a list endpoint", () => {
    const doc = JSON.stringify({
      openapi: "3.1.0",
      paths: {
        "/jobs": {
          get: {
            operationId: "listJobs",
            parameters: [
              { name: "limit", in: "query", schema: { type: "integer" } },
            ],
          },
        },
        "/orgs": {
          get: {
            operationId: "listOrgs",
            parameters: [{ $ref: "#/components/parameters/Limit" }],
          },
        },
        "/pages": {
          get: {
            operationId: "listPages",
            parameters: [
              {
                name: "limit",
                in: "query",
                required: true,
                schema: { type: "integer" },
              },
            ],
          },
        },
        "/jobs/{id}": {
          get: {
            parameters: [
              { name: "limit", in: "query", schema: { type: "integer" } },
            ],
          },
        },
      },
      components: {
        parameters: {
          Limit: { name: "limit", in: "query", schema: { type: "integer" } },
        },
      },
    });

    it("flags GET collection operations whose limit is not required", () => {
      const cwd = project({ "openapi.json": doc });
      const findings = pd111({
        cwd,
        config: { openapi: { doc: ["openapi.json"] } },
        files: nodeFiles,
        sources: () => [],
      });
      expect(targets(findings)).toStrictEqual([
        "openapi.json:GET /jobs",
        "openapi.json:GET /orgs",
      ]);
    });

    it("flags an optional limit in an MCP tool schema", () => {
      const findings = pd111({
        cwd: "/",
        config: {},
        files: nodeFiles,
        sources: () => [
          {
            file: "src/mcp.ts",
            text: `import { createMcp } from 'permdock/mcp';
const list = { inputSchema: z.object({ limit: z.number().optional(), cursor: z.string().optional() }) };
const ok = { inputSchema: z.object({ limit: z.number().max(100).default(20) }) };
const required = { inputSchema: z.object({ limit: z.number().max(100) }) };
`,
          },
          {
            file: "src/other.ts",
            text: "const x = z.object({ limit: z.number().optional() });",
          },
        ],
      });
      expect(targets(findings)).toStrictEqual(["src/mcp.ts:2"]);
    });
  });
});
