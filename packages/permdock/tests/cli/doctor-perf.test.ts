  describe("PD110 whole-token size", () => {
    it("measures the token the way the bench does", () => {
      expect(tokenChars({})).toBeGreaterThan(700);
      expect(
        tokenChars({ memberships: [{ id: "x".repeat(3_000) }] }),
      ).toBeGreaterThan(TOKEN_CHARS_BUDGET);
    });

    it("flags a hook sample whose token is over the budget", async () => {
      const big = { memberships: [{ id: "x".repeat(3_000) }] };
      const queries: string[] = [];
      const findings = await pd110(
        {
          cwd: "/",
          config: { supabase: { hook: {} } },
          files: nodeFiles,
          database: {
            url: "postgres://x",
            connect: () =>
              Promise.resolve({
                query: (sql: string) => {
                  queries.push(sql);
                  return Promise.resolve({
                    rows: sql.includes("custom_access_token_hook")
                      ? [{ claims: big }]
                      : [],
                  });
                },
                end: () => Promise.resolve(),
              }),
          },
        },
        [{ label: "a user with no rows", event: { user_id: "u" } }],
      );
      expect(findings).toHaveLength(1);
      expect(findings[0]?.code).toBe("PD110");
      expect(findings[0]?.message).toContain("a user with no rows");
      expect(queries).toContain("begin");
      expect(queries).toContain("rollback");
    });
  });

  describe("PD114 sample whose token is truncated", () => {
    it("is an error in jwt mode and absent in database mode", async () => {
      const truncated = { memberships: [], memberships_truncated: true };
      const run = (authorize: "jwt" | "database") =>
        pd110(
          {
            cwd: "/",
            config: { rls: { authorize }, supabase: { hook: {} } },
            files: nodeFiles,
            database: {
              url: "postgres://x",
              connect: () =>
                Promise.resolve({
                  query: (sql: string) =>
                    Promise.resolve({
                      rows: sql.includes("custom_access_token_hook")
                        ? [{ claims: truncated }]
                        : [],
                    }),
                  end: () => Promise.resolve(),
                }),
            },
          },
          [{ label: "a user in many organisations", event: { user_id: "u" } }],
        );
      expect((await run("jwt")).map((finding) => finding.code)).toContain(
        "PD114",
      );
      expect(
        (await run("database")).map((finding) => finding.code),
      ).not.toContain("PD114");
    });
  });

