import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

import type { PermDockConfig } from "../../src/cli/types.ts";

import { runPowerSync } from "../../src/cli/powersync/powersync.ts";
import { junctionMembershipSource } from "../../src/supabase/index.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const TMP = join(HERE, "../../tmp");
const FILE = "supabase/schemas/permdock/powersync_publication.sql";
const STATEMENT =
  "alter publication powersync add table permdock.custom_role_includes, permdock.custom_role_permissions, permdock.user_roles;";

const temps: string[] = [];

const DECLARED = "create publication powersync for tables in schema public;\n";

function project(publication: string | false): string {
  mkdirSync(TMP, { recursive: true });
  const dir = mkdtempSync(join(TMP, "powersync-publication-"));
  temps.push(dir);
  if (publication !== false) {
    mkdirSync(join(dir, "supabase/schemas/public"), { recursive: true });
    writeFileSync(
      join(dir, "supabase/schemas/public/powersync.sql"),
      publication,
    );
  }
  writeFileSync(
    join(dir, "policy.ts"),
    `import { allow, definePermissions, definePolicy, resource, role } from '${join(HERE, "../../src/index.ts")}';

export const permissions = definePermissions({
  job: resource({ id: 'id', actions: ['read'], relations: { tenant: { field: 'tenant_id', memberOf: 'tenant' } } }),
});

export const policy = definePolicy(permissions, {
  scopes: { tenant: { key: 'tenant_id' } },
  subject: () => null,
  roles: [role('owner', [allow(permissions.job.read)], { on: 'tenant' })],
});
`,
  );
  return dir;
}

const config: PermDockConfig = {
  policy: "policy.ts",
  rls: {
    authorize: "database",
    customRoles: true,
    tables: { job: "jobs" },
    membershipSources: [
      junctionMembershipSource({
        table: "tenant_users",
        scope: "tenant",
        id: "tenant_id",
        roles: "tier_role",
      }),
    ],
  },
  powersync: { resources: ["note"] },
};

describe("powersync generate: the publication under pg-delta", () => {
  afterEach(() => {
    for (const dir of temps.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("writes the tables outside public as a schema file and leaves the comment out of the yaml", async () => {
    const cwd = project(DECLARED);
    const result = await runPowerSync({
      cwd,
      config,
      check: false,
      rest: ["generate"],
    });
    expect(result.code).toBe(0);
    expect(result.output).toContain(`wrote ${FILE}`);
    expect(result.output).not.toContain("add the tables outside public");
    const sql = readFileSync(join(cwd, FILE), "utf8");
    expect(sql).toContain(STATEMENT);
    expect(sql.startsWith("-- Generated by permdock powersync generate")).toBe(
      true,
    );
    expect(readFileSync(join(cwd, "sync-config.yaml"), "utf8")).not.toContain(
      "powersync publication",
    );
    const check = await runPowerSync({
      cwd,
      config,
      check: true,
      rest: ["generate"],
    });
    expect(check.code).toBe(0);
    expect(check.output).toContain(`${FILE} is current`);
  });

  it("keeps the yaml comment without a schema directory", async () => {
    const cwd = project(false);
    const result = await runPowerSync({
      cwd,
      config,
      check: false,
      rest: ["generate"],
    });
    expect(result.output).toContain(
      `add the tables outside public to the powersync publication: ${STATEMENT}`,
    );
    expect(existsSync(join(cwd, FILE))).toBe(false);
    expect(readFileSync(join(cwd, "sync-config.yaml"), "utf8")).toContain(
      `# ${STATEMENT}`,
    );
  });

  for (const [label, publication] of [
    [
      "no schema file creates the powersync publication",
      "create table public.t (id int);\n",
    ],
    [
      "the publication is for all tables",
      "create publication powersync for all tables;\n",
    ],
  ] as const) {
    it(`keeps the yaml comment when ${label}`, async () => {
      const cwd = project(publication);
      const result = await runPowerSync({
        cwd,
        config,
        check: false,
        rest: ["generate"],
      });
      expect(result.output).toContain("add the tables outside public");
      expect(existsSync(join(cwd, FILE))).toBe(false);
    });
  }

  it("keeps the yaml comment under supabase.schemas migrations", async () => {
    const cwd = project(DECLARED);
    await runPowerSync({
      cwd,
      config: { ...config, supabase: { schemas: "migrations" } },
      check: false,
      rest: ["generate"],
    });
    expect(existsSync(join(cwd, FILE))).toBe(false);
  });
});
