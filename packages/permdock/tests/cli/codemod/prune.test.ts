import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { run } from "../../../src/cli/core/run.ts";
import { pd120 } from "../../../src/cli/doctor/restated-defaults.ts";
import {
  resolveConfig,
  restatedDefaults,
} from "../../../src/cli/project/resolve-config.ts";

const POLICY = `import { allow, definePermissions, definePolicy, resource, role } from "permdock";

export const permissions = definePermissions({
  note: resource({ actions: ["read"], relations: { org: { field: "orgId", memberOf: "tenant" } } }),
});

export const policy = definePolicy(permissions, {
  scopes: { tenant: { key: "orgId" } },
  subject: () => null,
  roles: [role("reader", [allow(permissions.note.read)], { on: "tenant" })],
});
`;

const dirs: string[] = [];

function project(emit: string, rls: string): string {
  const cwd = mkdtempSync(join(tmpdir(), "permdock-prune-"));
  dirs.push(cwd);
  writeFileSync(join(cwd, "policy.ts"), POLICY);
  writeFileSync(
    join(cwd, "permdock.config.ts"),
    `import { definePlugin } from "permdock/cli";
const echo = definePlugin({
  name: "echo",
  version: "1",
  plan: () => [{ id: "echo", out: "echo.txt" }],
  emit: (_task, _model, source) => [{ path: "echo.txt", contents: ${emit} }],
});
export default {
  policy: "./policy.ts",
  plugins: [echo],
  rls: {
    // The helper schema.
    ${rls}
  },
};
`,
  );
  return cwd;
}

describe("codemod config --prune", () => {
  afterEach(() => {
    for (const dir of dirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("removes keys equal to their default when every output stays the same", async () => {
    const cwd = project(
      '`${source.config.rls?.schema ?? "permdock"}|${source.config.rls?.gucPrefix ?? "app"}\\n`',
      'schema: "permdock",\n    gucPrefix: "app",\n    roleClaim: "role",',
    );
    const check = await run(["codemod", "config", "--prune", "--check"], {
      cwd,
    });
    expect(check.code).toBe(1);
    expect(check.stdout).toContain("would remove 2 keys");
    const result = await run(["codemod", "config", "--prune", "--force"], {
      cwd,
    });
    expect(result.code).toBe(0);
    const text = readFileSync(join(cwd, "permdock.config.ts"), "utf8");
    expect(text).not.toContain("schema:");
    expect(text).not.toContain("gucPrefix:");
    expect(text).not.toContain("The helper schema");
    expect(text).toContain('roleClaim: "role"');
    const again = await run(["codemod", "config", "--prune", "--check"], {
      cwd,
    });
    expect(again.code).toBe(0);
  });

  it("keeps a key whose removal changes a generated byte", async () => {
    const cwd = project(
      "`${JSON.stringify(source.config.rls)}\\n`",
      'schema: "permdock",',
    );
    const result = await run(
      ["codemod", "config", "--prune", "--force", "--json"],
      { cwd },
    );
    expect(result.code).toBe(0);
    expect(JSON.parse(result.stdout).data).toMatchObject({
      removed: [],
      kept: [{ key: "rls.schema" }],
    });
    expect(readFileSync(join(cwd, "permdock.config.ts"), "utf8")).toContain(
      'schema: "permdock"',
    );
  });

  it("refuses codemod config without --prune", async () => {
    const result = await run(["codemod", "config"], {
      cwd: project('"x\\n"', ""),
    });
    expect(result.code).toBe(2);
    expect(result.stderr).toContain("--prune");
  });
});

describe(resolveConfig, () => {
  it("fills unset keys of an opened section only", () => {
    const resolved = resolveConfig({ rls: { schema: "auth_x" } });
    expect(resolved.value.rls?.schema).toBe("auth_x");
    expect(resolved.value.rls?.gucPrefix).toBe("app");
    expect(resolved.value.supabase).toBeUndefined();
    expect(resolved.defaults).toContain("rls.gucPrefix");
    expect(resolved.defaults).not.toContain("rls.schema");
  });

  it("compares lists whose order no command reads as sets", () => {
    expect(
      restatedDefaults({ collect: { srcPath: ["./src"] } }).map((entry) =>
        entry.path.join("."),
      ),
    ).toStrictEqual(["collect.srcPath"]);
    expect(
      restatedDefaults({
        doctor: {
          sensitiveActions: [
            "pay",
            "approve",
            "settle",
            "submit",
            "transfer",
            "refund",
            "disburse",
          ],
        },
      }),
    ).toHaveLength(1);
  });
});

describe("PD120", () => {
  it("names each key set to its default", () => {
    expect(
      pd120({ rls: { schema: "permdock", gucPrefix: "custom" } }),
    ).toStrictEqual([
      expect.objectContaining({ code: "PD120", target: "rls.schema" }),
    ]);
  });
});
