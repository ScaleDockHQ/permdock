import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import { Client } from "pg";

import { startDatabase } from "./database.ts";

const root = path.join(import.meta.dirname, "..");
const benchDir = path.join(import.meta.dirname, "explain-bench");
const USER = "11111111-1111-4111-8111-111111111111";

/**
 * Plans `public.explain_ten_tables()` as a member of five organisations with
 * `better-supabase doctor --explain ... --as`, over the helpers the installed
 * `permdock` generates. Run it once per `permdock` build and compare the
 * printed doctor output. `--memo better-supabase` generates the helpers over
 * `better_supabase.memo_get/memo_set`; `--sql <file>` applies helpers another
 * build generated; `--doctor <bin>` names a better-supabase CLI with `doctor
 * --explain <function>`.
 */
function generated(memo: string | undefined): string {
  const config =
    memo === "better-supabase" ? ["--config", "better-supabase.config.ts"] : [];
  const result = spawnSync(
    path.join(root, "node_modules/.bin/permdock"),
    ["generate", "--only", "rls", "--no-cache", ...config],
    { cwd: benchDir, encoding: "utf8" },
  );
  if (result.status !== 0) {
    throw new Error(
      `permdock generate --only rls failed: ${result.stderr}${result.stdout}`,
    );
  }
  return readFileSync(path.join(benchDir, "bench.sql"), "utf8");
}

function flag(name: string): string | undefined {
  const at = process.argv.indexOf(name);
  return at === -1 ? undefined : process.argv[at + 1];
}

const memo = flag("--memo");
// A helpers file generated by another permdock build, and a better-supabase CLI that has `doctor --explain <function>`.
const sqlFile = flag("--sql");
const doctorBin =
  flag("--doctor") ?? path.join(root, "node_modules/.bin/better-supabase");
const database = await startDatabase();
try {
  const client = new Client({ connectionString: database.url });
  await client.connect();
  try {
    await client.query(
      readFileSync(path.join(import.meta.dirname, "explain-bench.sql"), "utf8"),
    );
    await client.query(
      sqlFile === undefined ? generated(memo) : readFileSync(sqlFile, "utf8"),
    );
  } finally {
    await client.end();
  }
  const doctor = spawnSync(
    doctorBin,
    ["doctor", "--explain", "public.explain_ten_tables", "--as", USER],
    {
      cwd: root,
      stdio: "inherit",
      env: { ...process.env, DATABASE_URL: "", SUPABASE_DB_URL: database.url },
    },
  );
  process.exitCode = doctor.status ?? 1;
} finally {
  await database.stop();
}
